#!/usr/bin/env python3
"""Run rolling time-series cross-validation for the `model/new` pipeline."""

from __future__ import annotations

import argparse
import itertools
import json
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Tuple

import joblib
import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (
    accuracy_score,
    average_precision_score,
    f1_score,
    precision_score,
    recall_score,
    roc_auc_score,
)
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler
from xgboost import XGBClassifier


FEATURE_COLS = [
    "hardship_index",
    "spatial_lag_hardship",
    "spatial_lag_crime_lag1",
    "arrest_rate",
    "top_type_share",
]


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--data",
        default="data_processed/geo_model_dataset.csv",
        help="Path to dataset generated by model/new/02_make_features_label.py",
    )
    parser.add_argument(
        "--output-dir",
        default="experiment/new_cross_validation",
        help="Root output directory for cross-validation artifacts.",
    )
    parser.add_argument(
        "--outer-years",
        nargs="+",
        type=int,
        default=[2020, 2021, 2022, 2023, 2024],
        help="Validation years for rolling cross-validation.",
    )
    parser.add_argument(
        "--holdout-year",
        type=int,
        default=2025,
        help="Optional untouched year for final reference evaluation.",
    )
    parser.add_argument("--seed", type=int, default=42)
    return parser.parse_args()


def safe_roc_auc(y_true: np.ndarray, prob: np.ndarray) -> float:
    if len(np.unique(y_true)) < 2:
        return float("nan")
    return float(roc_auc_score(y_true, prob))


def metric_bundle(y_true: np.ndarray, prob: np.ndarray, threshold: float) -> Dict[str, float]:
    pred = (prob >= threshold).astype(int)
    return {
        "roc_auc": safe_roc_auc(y_true, prob),
        "pr_auc": float(average_precision_score(y_true, prob)),
        "f1": float(f1_score(y_true, pred, zero_division=0)),
        "recall": float(recall_score(y_true, pred, zero_division=0)),
        "precision": float(precision_score(y_true, pred, zero_division=0)),
        "accuracy": float(accuracy_score(y_true, pred)),
    }


def pick_best_threshold(y_true: np.ndarray, prob: np.ndarray) -> float:
    thresholds = np.linspace(0.05, 0.95, 181)
    best_threshold = 0.5
    best_f1 = -1.0
    for t in thresholds:
        f1 = f1_score(y_true, (prob >= t).astype(int), zero_division=0)
        if f1 > best_f1:
            best_f1 = f1
            best_threshold = float(t)
    return best_threshold


def iter_param_grid(grid: Dict[str, Iterable]) -> Iterable[Dict[str, object]]:
    keys = list(grid.keys())
    values = [list(grid[k]) for k in keys]
    for combo in itertools.product(*values):
        yield dict(zip(keys, combo))


def build_lr(params: Dict[str, object], seed: int) -> Pipeline:
    clf = LogisticRegression(
        random_state=seed,
        max_iter=2000,
        solver="liblinear",
        class_weight="balanced",
        **params,
    )
    return Pipeline([("scaler", StandardScaler()), ("clf", clf)])


def build_rf(params: Dict[str, object], seed: int) -> RandomForestClassifier:
    return RandomForestClassifier(
        random_state=seed,
        n_jobs=-1,
        class_weight="balanced_subsample",
        **params,
    )


def build_xgb(params: Dict[str, object], seed: int, scale_pos_weight: float) -> XGBClassifier:
    return XGBClassifier(
        random_state=seed,
        objective="binary:logistic",
        tree_method="hist",
        eval_metric="auc",
        n_jobs=-1,
        scale_pos_weight=scale_pos_weight,
        **params,
    )


def build_model_specs(seed: int, scale_pos_weight: float) -> Dict[str, Dict[str, object]]:
    return {
        "logistic_regression": {
            "builder": lambda p: build_lr(p, seed),
            "params": {"C": [0.01, 0.05, 0.1, 0.5, 1.0, 2.0]},
        },
        "random_forest": {
            "builder": lambda p: build_rf(p, seed),
            "params": {
                "n_estimators": [300, 500],
                "max_depth": [6, 10, None],
                "min_samples_leaf": [1, 5],
                "max_features": ["sqrt", 0.7],
            },
        },
        "xgboost": {
            "builder": lambda p: build_xgb(p, seed, scale_pos_weight),
            "params": {
                "n_estimators": [300],
                "max_depth": [3, 5],
                "learning_rate": [0.05, 0.1],
                "subsample": [0.8, 1.0],
                "colsample_bytree": [0.8, 1.0],
                "reg_lambda": [1.0, 5.0],
            },
        },
    }


def class_weight_ratio(y: np.ndarray) -> float:
    pos = int(y.sum())
    neg = int(len(y) - pos)
    return (neg / pos) if pos > 0 else 1.0


def year_window(df: pd.DataFrame, year: int) -> pd.DataFrame:
    start = pd.Timestamp(year=year, month=1, day=1)
    end = pd.Timestamp(year=year + 1, month=1, day=1)
    return df[(df["target_month"] >= start) & (df["target_month"] < end)].copy()


def before_year(df: pd.DataFrame, year: int) -> pd.DataFrame:
    cutoff = pd.Timestamp(year=year, month=1, day=1)
    return df[df["target_month"] < cutoff].copy()


def prediction_base_cols(df: pd.DataFrame) -> List[str]:
    cols = []
    for col in ["community_area", "month", "target_month", "label"]:
        if col in df.columns:
            cols.append(col)
    return cols


def tune_on_inner_split(
    inner_train_df: pd.DataFrame,
    inner_val_df: pd.DataFrame,
    seed: int,
) -> Tuple[List[Dict[str, object]], Dict[str, Dict[str, object]]]:
    X_train = inner_train_df[FEATURE_COLS].to_numpy(dtype=float)
    y_train = inner_train_df["label"].to_numpy(dtype=int)
    X_val = inner_val_df[FEATURE_COLS].to_numpy(dtype=float)
    y_val = inner_val_df["label"].to_numpy(dtype=int)

    if len(np.unique(y_train)) < 2:
        raise ValueError("Inner training labels contain only one class.")

    train_ratio = class_weight_ratio(y_train)
    specs = build_model_specs(seed=seed, scale_pos_weight=train_ratio)

    search_rows: List[Dict[str, object]] = []
    best_payloads: Dict[str, Dict[str, object]] = {}

    for model_name, spec in specs.items():
        best_score = -np.inf
        best_metric = "roc_auc"
        best_params: Dict[str, object] = {}
        best_prob_val = None

        for params in iter_param_grid(spec["params"]):
            model = spec["builder"](params)
            model.fit(X_train, y_train)
            prob_val = model.predict_proba(X_val)[:, 1]

            auc = safe_roc_auc(y_val, prob_val)
            pr = float(average_precision_score(y_val, prob_val))
            if np.isfinite(auc):
                selection_metric = "roc_auc"
                selection_score = float(auc)
            else:
                selection_metric = "accuracy_fallback"
                selection_score = float(accuracy_score(y_val, (prob_val >= 0.5).astype(int)))

            search_rows.append(
                {
                    "model": model_name,
                    "params": json.dumps(params, sort_keys=True),
                    "inner_val_roc_auc": float(auc),
                    "inner_val_pr_auc": pr,
                    "selection_metric": selection_metric,
                    "selection_score": selection_score,
                }
            )

            if selection_score > best_score:
                best_score = selection_score
                best_metric = selection_metric
                best_params = dict(params)
                best_prob_val = prob_val

        if best_prob_val is None:
            raise RuntimeError(f"Failed to tune model={model_name}")

        threshold = pick_best_threshold(y_val, best_prob_val)
        best_payloads[model_name] = {
            "best_params": best_params,
            "best_threshold": threshold,
            "selection_metric": best_metric,
            "selection_score": float(best_score),
            "inner_val_metrics": metric_bundle(y_val, best_prob_val, threshold),
        }

    return search_rows, best_payloads


def evaluate_outer_fold(
    fold_year: int,
    outer_train_df: pd.DataFrame,
    outer_val_df: pd.DataFrame,
    best_payloads: Dict[str, Dict[str, object]],
    seed: int,
    fold_model_dir: Path,
    reports_dir: Path,
) -> List[Dict[str, object]]:
    X_train = outer_train_df[FEATURE_COLS].to_numpy(dtype=float)
    y_train = outer_train_df["label"].to_numpy(dtype=int)
    X_val = outer_val_df[FEATURE_COLS].to_numpy(dtype=float)
    y_val = outer_val_df["label"].to_numpy(dtype=int)

    outer_ratio = class_weight_ratio(y_train)
    specs = build_model_specs(seed=seed, scale_pos_weight=outer_ratio)
    rows: List[Dict[str, object]] = []
    id_cols = prediction_base_cols(outer_val_df)

    fold_model_dir.mkdir(parents=True, exist_ok=True)
    reports_dir.mkdir(parents=True, exist_ok=True)

    for model_name, payload in best_payloads.items():
        params = payload["best_params"]
        threshold = float(payload["best_threshold"])
        model = specs[model_name]["builder"](params)
        model.fit(X_train, y_train)
        prob_val = model.predict_proba(X_val)[:, 1]
        outer_metrics = metric_bundle(y_val, prob_val, threshold)

        rows.append(
            {
                "fold_year": fold_year,
                "model": model_name,
                "n_train": int(len(outer_train_df)),
                "n_val": int(len(outer_val_df)),
                "train_label_rate": float(y_train.mean()),
                "val_label_rate": float(y_val.mean()),
                "threshold": threshold,
                "selection_metric": payload["selection_metric"],
                "selection_score": float(payload["selection_score"]),
                "inner_val_roc_auc": float(payload["inner_val_metrics"]["roc_auc"]),
                "inner_val_pr_auc": float(payload["inner_val_metrics"]["pr_auc"]),
                "outer_val_roc_auc": outer_metrics["roc_auc"],
                "outer_val_pr_auc": outer_metrics["pr_auc"],
                "outer_val_f1": outer_metrics["f1"],
                "outer_val_recall": outer_metrics["recall"],
                "outer_val_precision": outer_metrics["precision"],
                "outer_val_accuracy": outer_metrics["accuracy"],
                "best_params": json.dumps(params, sort_keys=True),
            }
        )

        pred_df = outer_val_df[id_cols].copy()
        pred_df["pred_prob"] = prob_val
        pred_df["pred_label"] = (prob_val >= threshold).astype(int)
        pred_df.to_csv(reports_dir / f"fold_{fold_year}_predictions_{model_name}.csv", index=False)

        param_payload = {
            "fold_year": fold_year,
            "model": model_name,
            "seed": seed,
            "feature_columns": FEATURE_COLS,
            "best_params": params,
            "best_threshold": threshold,
            "selection_metric": payload["selection_metric"],
            "selection_score": float(payload["selection_score"]),
            "inner_val_metrics": payload["inner_val_metrics"],
            "outer_val_metrics": outer_metrics,
            "outer_train_scale_pos_weight": outer_ratio,
        }
        (fold_model_dir / f"{model_name}_best_params.json").write_text(
            json.dumps(param_payload, indent=2),
            encoding="utf-8",
        )
        joblib.dump(model, fold_model_dir / f"{model_name}_outer_fold_model.joblib")

    return rows


def build_holdout_reference(
    df: pd.DataFrame,
    holdout_year: int,
    seed: int,
    best_model_name: str,
    models_dir: Path,
    reports_dir: Path,
) -> Optional[pd.DataFrame]:
    holdout_df = year_window(df, holdout_year)
    pre_holdout_df = before_year(df, holdout_year)
    tuning_val_df = year_window(df, holdout_year - 1)
    tuning_train_df = before_year(df, holdout_year - 1)
    if holdout_df.empty or pre_holdout_df.empty or tuning_val_df.empty or tuning_train_df.empty:
        return None

    search_rows, best_payloads = tune_on_inner_split(
        inner_train_df=tuning_train_df,
        inner_val_df=tuning_val_df,
        seed=seed,
    )
    pd.DataFrame(search_rows).to_csv(reports_dir / "holdout_tuning_search_results.csv", index=False)

    chosen = best_payloads[best_model_name]
    y_train = pre_holdout_df["label"].to_numpy(dtype=int)
    holdout_ratio = class_weight_ratio(y_train)
    model = build_model_specs(seed=seed, scale_pos_weight=holdout_ratio)[best_model_name]["builder"](chosen["best_params"])
    model.fit(pre_holdout_df[FEATURE_COLS].to_numpy(dtype=float), y_train)

    X_holdout = holdout_df[FEATURE_COLS].to_numpy(dtype=float)
    y_holdout = holdout_df["label"].to_numpy(dtype=int)
    prob_holdout = model.predict_proba(X_holdout)[:, 1]
    threshold = float(chosen["best_threshold"])
    holdout_metrics = metric_bundle(y_holdout, prob_holdout, threshold)

    reports_dir.mkdir(parents=True, exist_ok=True)
    models_dir.mkdir(parents=True, exist_ok=True)

    holdout_pred = holdout_df[prediction_base_cols(holdout_df)].copy()
    holdout_pred["pred_prob"] = prob_holdout
    holdout_pred["pred_label"] = (prob_holdout >= threshold).astype(int)
    holdout_pred.to_csv(reports_dir / f"holdout_{holdout_year}_predictions_{best_model_name}.csv", index=False)

    payload = {
        "holdout_year": holdout_year,
        "model": best_model_name,
        "seed": seed,
        "feature_columns": FEATURE_COLS,
        "best_params": chosen["best_params"],
        "best_threshold": threshold,
        "inner_val_metrics": chosen["inner_val_metrics"],
        "holdout_metrics": holdout_metrics,
        "pre_holdout_scale_pos_weight": holdout_ratio,
    }
    (models_dir / f"holdout_{holdout_year}_{best_model_name}_best_params.json").write_text(
        json.dumps(payload, indent=2),
        encoding="utf-8",
    )
    joblib.dump(model, models_dir / f"holdout_{holdout_year}_{best_model_name}_model.joblib")

    return pd.DataFrame(
        [
            {
                "holdout_year": holdout_year,
                "model": best_model_name,
                "threshold": threshold,
                "holdout_roc_auc": holdout_metrics["roc_auc"],
                "holdout_pr_auc": holdout_metrics["pr_auc"],
                "holdout_f1": holdout_metrics["f1"],
                "holdout_recall": holdout_metrics["recall"],
                "holdout_precision": holdout_metrics["precision"],
                "holdout_accuracy": holdout_metrics["accuracy"],
            }
        ]
    )


def build_summary_markdown(
    out_path: Path,
    fold_df: pd.DataFrame,
    summary_df: pd.DataFrame,
    fold_meta_df: pd.DataFrame,
    best_model_counts_df: pd.DataFrame,
    holdout_df: Optional[pd.DataFrame],
) -> None:
    lines = [
        "# New Method Cross-Validation Summary",
        "",
        "## Setup",
        "- Method: rolling expanding-window time-series cross-validation.",
        "- Features: hardship_index, spatial_lag_hardship, spatial_lag_crime_lag1, arrest_rate, top_type_share.",
        "- Outer folds: validate on one full year at a time, train on all prior years.",
        "- Inner tuning: use the immediately preceding year as the tuning window for hyperparameter selection and threshold selection.",
        "",
        "## Fold Definitions",
        fold_meta_df.to_string(index=False),
        "",
        "## Aggregate CV Performance",
        summary_df.to_string(index=False),
        "",
        "## Best Model Count by Fold (outer ROC-AUC)",
        best_model_counts_df.to_string(index=False),
        "",
        "## Per-Fold Metrics",
        fold_df.to_string(index=False),
        "",
    ]

    if holdout_df is not None and not holdout_df.empty:
        lines.extend(
            [
                "## Holdout Reference",
                holdout_df.to_string(index=False),
                "",
            ]
        )

    out_path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    args = parse_args()
    np.random.seed(args.seed)

    data_path = Path(args.data)
    if not data_path.exists():
        raise FileNotFoundError(f"Missing dataset: {data_path}")

    output_root = Path(args.output_dir)
    models_dir = output_root / "models"
    reports_dir = output_root / "reports"
    models_dir.mkdir(parents=True, exist_ok=True)
    reports_dir.mkdir(parents=True, exist_ok=True)

    date_cols = [c for c in ["month", "target_month"] if c in pd.read_csv(data_path, nrows=0).columns]
    df = pd.read_csv(data_path, parse_dates=date_cols)

    required = set(FEATURE_COLS + ["label", "target_month"])
    missing = [c for c in required if c not in df.columns]
    if missing:
        raise ValueError(f"Dataset missing required columns: {missing}")

    model_df = df.dropna(subset=FEATURE_COLS + ["label", "target_month"]).copy()
    model_df["target_month"] = pd.to_datetime(model_df["target_month"], errors="coerce")
    model_df = model_df.dropna(subset=["target_month"]).copy()

    outer_years = sorted(args.outer_years)
    if len(outer_years) < 2:
        raise ValueError("At least two outer years are recommended for cross-validation.")

    fold_meta_rows: List[Dict[str, object]] = []
    search_rows_all: List[Dict[str, object]] = []
    fold_rows_all: List[Dict[str, object]] = []

    for fold_year in outer_years:
        outer_train_df = before_year(model_df, fold_year)
        outer_val_df = year_window(model_df, fold_year)
        inner_train_df = before_year(model_df, fold_year - 1)
        inner_val_df = year_window(model_df, fold_year - 1)

        if outer_train_df.empty or outer_val_df.empty or inner_train_df.empty or inner_val_df.empty:
            raise ValueError(f"Empty split encountered for fold_year={fold_year}")

        fold_meta_rows.append(
            {
                "fold_year": fold_year,
                "inner_train_rows": int(len(inner_train_df)),
                "inner_val_rows": int(len(inner_val_df)),
                "outer_train_rows": int(len(outer_train_df)),
                "outer_val_rows": int(len(outer_val_df)),
                "inner_train_label_rate": float(inner_train_df["label"].mean()),
                "inner_val_label_rate": float(inner_val_df["label"].mean()),
                "outer_train_label_rate": float(outer_train_df["label"].mean()),
                "outer_val_label_rate": float(outer_val_df["label"].mean()),
            }
        )

        print(f"[CV] Fold {fold_year}: tuning on {fold_year - 1}, evaluating on {fold_year}")
        search_rows, best_payloads = tune_on_inner_split(
            inner_train_df=inner_train_df,
            inner_val_df=inner_val_df,
            seed=args.seed,
        )
        for row in search_rows:
            row["fold_year"] = fold_year
        search_rows_all.extend(search_rows)

        fold_rows = evaluate_outer_fold(
            fold_year=fold_year,
            outer_train_df=outer_train_df,
            outer_val_df=outer_val_df,
            best_payloads=best_payloads,
            seed=args.seed,
            fold_model_dir=models_dir / f"fold_{fold_year}",
            reports_dir=reports_dir,
        )
        fold_rows_all.extend(fold_rows)

    fold_meta_df = pd.DataFrame(fold_meta_rows).sort_values("fold_year").reset_index(drop=True)
    fold_meta_df.to_csv(reports_dir / "fold_definitions.csv", index=False)

    search_df = pd.DataFrame(search_rows_all).sort_values(
        ["fold_year", "model", "selection_score"],
        ascending=[True, True, False],
    )
    search_df.to_csv(reports_dir / "cv_search_results.csv", index=False)

    fold_df = pd.DataFrame(fold_rows_all).sort_values(["fold_year", "outer_val_roc_auc"], ascending=[True, False])
    fold_df.to_csv(reports_dir / "cv_fold_metrics.csv", index=False)

    summary_df = (
        fold_df.groupby("model", as_index=False)
        .agg(
            n_folds=("fold_year", "count"),
            mean_outer_val_roc_auc=("outer_val_roc_auc", "mean"),
            std_outer_val_roc_auc=("outer_val_roc_auc", "std"),
            mean_outer_val_pr_auc=("outer_val_pr_auc", "mean"),
            std_outer_val_pr_auc=("outer_val_pr_auc", "std"),
            mean_outer_val_f1=("outer_val_f1", "mean"),
            std_outer_val_f1=("outer_val_f1", "std"),
            mean_outer_val_recall=("outer_val_recall", "mean"),
            mean_outer_val_precision=("outer_val_precision", "mean"),
            mean_outer_val_accuracy=("outer_val_accuracy", "mean"),
        )
        .sort_values(["mean_outer_val_roc_auc", "mean_outer_val_pr_auc"], ascending=[False, False])
        .reset_index(drop=True)
    )
    summary_df.to_csv(reports_dir / "cv_summary.csv", index=False)

    best_by_fold = (
        fold_df.sort_values(["fold_year", "outer_val_roc_auc", "outer_val_pr_auc"], ascending=[True, False, False])
        .groupby("fold_year", as_index=False)
        .head(1)
    )
    best_model_counts_df = (
        best_by_fold.groupby("model", as_index=False)
        .size()
        .rename(columns={"size": "best_fold_count"})
        .sort_values("best_fold_count", ascending=False)
        .reset_index(drop=True)
    )
    best_model_counts_df.to_csv(reports_dir / "best_model_counts.csv", index=False)

    holdout_df: Optional[pd.DataFrame] = None
    if args.holdout_year is not None and not summary_df.empty:
        best_model_name = str(summary_df.iloc[0]["model"])
        holdout_df = build_holdout_reference(
            df=model_df,
            holdout_year=int(args.holdout_year),
            seed=args.seed,
            best_model_name=best_model_name,
            models_dir=models_dir,
            reports_dir=reports_dir,
        )
        if holdout_df is not None:
            holdout_df.to_csv(reports_dir / "holdout_metrics.csv", index=False)

    build_summary_markdown(
        out_path=reports_dir / "summary.md",
        fold_df=fold_df,
        summary_df=summary_df,
        fold_meta_df=fold_meta_df,
        best_model_counts_df=best_model_counts_df,
        holdout_df=holdout_df,
    )

    print(f"Saved cross-validation reports to: {reports_dir}")


if __name__ == "__main__":
    main()
